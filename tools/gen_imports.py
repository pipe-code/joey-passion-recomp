"""Emit a C table of the exe's imports: IAT slot address, DLL and function name.
Usage: python -I tools/gen_imports.py game/Joey_Pc.exe build/all/imports.h"""
import sys, pefile
pe = pefile.PE(sys.argv[1])
rows = [(i.address, e.dll.decode(), i.name.decode()) for e in pe.DIRECTORY_ENTRY_IMPORT for i in e.imports]
with open(sys.argv[2], "w") as f:
    f.write("/* generated by tools/gen_imports.py */\n")
    f.write("typedef struct { uint32_t iat; const char *dll, *name; } ImportDesc;\n")
    f.write(f"#define NUM_IMPORTS {len(rows)}\nstatic const ImportDesc IMPORTS[NUM_IMPORTS] = {{\n")
    for a, d, n in rows:
        f.write(f'  {{0x{a:x}u, "{d}", "{n}"}},\n')
    f.write("};\n")
print(len(rows), "imports")
